"""Local filesystem archive: Markdown records + JSON index.

Layout (default ``~/.vidchat/research``):
    <session-id>.md      permanent local record for one video
    index.json           list of session records for later searching

The remote notebook is the interactive workspace; the local Markdown file is
the permanent record. Either can be retained without the other.
"""

from __future__ import annotations

import datetime as _dt
import json
import os
import re
from dataclasses import dataclass, field
from pathlib import Path

DEFAULT_RESEARCH_DIR = Path(os.environ.get("VIDCHAT_RESEARCH_DIR", Path.home() / ".vidchat" / "research"))

INDEX_FILENAME = "index.json"


@dataclass
class Turn:
    question: str
    answer: str


@dataclass
class Session:
    session_id: str
    video_url: str
    title: str
    notebook_id: str | None
    notebook_kept: bool = False
    created_at: str = ""
    summary: str = ""
    turns: list[Turn] = field(default_factory=list)
    markdown_path: str | None = None
    decision: str = "pending"  # pending|kept|archived|deleted|deleted-saved

    def to_index_record(self) -> dict:
        return {
            "session_id": self.session_id,
            "video_url": self.video_url,
            "title": self.title,
            "notebook_id": self.notebook_id,
            "notebook_kept": self.notebook_kept,
            "created_at": self.created_at,
            "markdown_path": self.markdown_path,
            "turn_count": len(self.turns),
            "decision": self.decision,
        }


def utcnow_iso() -> str:
    return _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds")


def slugify(text: str, max_len: int = 60) -> str:
    """Filesystem-safe slug. Extracts a YouTube video id when present."""
    video_id = extract_youtube_id(text)
    base = video_id or text.lower()
    if not video_id:
        base = re.sub(r"https?://(www\.)?", "", base)
        base = re.sub(r"[^a-z0-9]+", "-", base)
    slug = re.sub(r"-+", "-", base).strip("-")[:max_len].strip("-")
    return slug or "video"


def extract_youtube_id(url: str) -> str | None:
    m = re.search(r"(?:v=|youtu\.be/|/shorts/|/embed/)([A-Za-z0-9_-]{6,})", url)
    return m.group(1)[:32] if m else None


def make_session_id(video_url: str, now: _dt.datetime | None = None) -> str:
    now = now or _dt.datetime.now()
    stamp = now.strftime("%Y%m%d-%H%M%S")
    return f"{stamp}-{slugify(video_url)}"


def render_markdown(session: Session) -> str:
    lines = [
        f"# {session.title or session.video_url}",
        "",
        f"- video_url: {session.video_url}",
        f"- notebook_id: {session.notebook_id or 'n/a'}",
        f"- notebook_kept: {'yes' if session.notebook_kept else 'no'}",
        f"- created_at: {session.created_at}",
        f"- session_id: {session.session_id}",
        "",
        "## Strategy summary",
        "",
        session.summary.strip() or "_No summary recorded._",
        "",
    ]
    if session.turns:
        lines += ["## Follow-up conversation", ""]
        for i, turn in enumerate(session.turns, 1):
            lines += [
                f"### Q{i}",
                "",
                f"**Q:** {turn.question.strip()}",
                "",
                turn.answer.strip() or "_No answer recorded._",
                "",
            ]
    else:
        lines += ["## Follow-up conversation", "", "_No follow-up questions asked._", ""]
    lines += [
        "---",
        "_Generated by vidchat. Performance figures above are claims made in the",
        "video, not verified results._",
        "",
    ]
    return "\n".join(lines)


def ensure_research_dir(path: Path | str | None = None) -> Path:
    directory = Path(path) if path else DEFAULT_RESEARCH_DIR
    directory.mkdir(parents=True, exist_ok=True)
    return directory


def save_session(session: Session, research_dir: Path | str | None = None) -> Path:
    """Write the Markdown archive and upsert the JSON index. Returns md path."""
    directory = ensure_research_dir(research_dir)
    md_path = directory / f"{session.session_id}.md"
    md_path.write_text(render_markdown(session), encoding="utf-8")
    session.markdown_path = str(md_path)
    upsert_index(session, directory)
    return md_path


def _index_path(research_dir: Path) -> Path:
    return research_dir / INDEX_FILENAME


def load_index(research_dir: Path | str | None = None) -> list[dict]:
    directory = ensure_research_dir(research_dir)
    path = _index_path(directory)
    if not path.exists():
        return []
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        return data if isinstance(data, list) else []
    except (json.JSONDecodeError, OSError):
        return []


def upsert_index(session: Session, research_dir: Path | str | None = None) -> list[dict]:
    directory = ensure_research_dir(research_dir)
    records = load_index(directory)
    record = session.to_index_record()
    for i, existing in enumerate(records):
        if existing.get("session_id") == session.session_id:
            records[i] = record
            break
    else:
        records.append(record)
    # newest first
    records.sort(key=lambda r: r.get("created_at", ""), reverse=True)
    _index_path(directory).write_text(json.dumps(records, indent=2), encoding="utf-8")
    return records


def find_record(research_dir: Path | str, session_id: str) -> dict | None:
    for record in load_index(research_dir):
        if record.get("session_id") == session_id or record.get("session_id", "").startswith(session_id):
            return record
    return None
